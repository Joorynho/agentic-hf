def _pct_fraction(v: float) -> float:
    n = float(v)
    if n > 1.0 and n <= 100.0:
        n = n / 100.0
    return n


PositivePct = Annotated[float, BeforeValidator(_pct_fraction), Field(gt=0.0)]
FractionPct = Annotated[float, BeforeValidator(_pct_fraction), Field(gt=0.0, le=1.0)]


class TakeProfitLevel(BaseModel):
    """One optional scale-out level for a position.

    `trigger_pct` and `close_pct` are decimal fractions: 0.08 means +8% and
    0.25 means close 25% of the then-open position.
    """

    trigger_pct: PositivePct
    close_pct: FractionPct = 0.25
    trail_stop_pct: PositivePct | None = None
    label: str = ""

    @model_validator(mode="before")
    @classmethod
    def normalize_aliases(cls, data):
        if not isinstance(data, dict):
            return data
        out = dict(data)
        if "trigger_pct" not in out:
            out["trigger_pct"] = (
                out.get("pct")
                or out.get("profit_pct")
                or out.get("target_pct")
                or out.get("take_profit_pct")
            )
        if "close_pct" not in out:
            out["close_pct"] = (
                out.get("exit_pct")
                or out.get("qty_pct")
                or out.get("close_fraction")
                or out.get("fraction")
            )
        return out


