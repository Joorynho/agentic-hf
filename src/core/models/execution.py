class PositionSnapshot(BaseModel):
    """Snapshot of an open position with current market data."""
    symbol: str
    qty: float  # Positive = long, negative = short
    cost_basis: float  # Average cost per share
    current_price: float  # Current market price
    unrealized_pnl: float  # qty * (current_price - cost_basis)
    entry_thesis: str = ""
    entry_date: str = ""
    stop_loss_pct: float = 0.05
    take_profit_pct: float = 0.15
    take_profit_levels: list[dict] = Field(default_factory=list)
    take_profit_hits: list[int] = Field(default_factory=list)
    max_hold_days: int = 0
    conviction: float = 0.0
    thesis_status: str = "unknown"
    thesis_issues: list[str] = Field(default_factory=list)
    thesis_review: dict = Field(default_factory=dict)
    evidence_packet: dict = Field(default_factory=dict)
    price_source: str = ""
    price_updated_at: str = ""
    price_stale: bool = False

    @property
    def notional(self) -> float:
        """Notional value of position at current price."""
        return self.qty * self.current_price

    @property
    def current_notional(self) -> float:
        """Current market value of the position."""
        return self.qty * self.current_price

    @property
    def entry_notional(self) -> float:
        """Original cost-basis value of the current open quantity."""
        return self.qty * self.cost_basis

    @property
    def pnl_pct(self) -> float:
        """PnL as percentage of cost basis."""
        if self.cost_basis == 0:
            return 0.0
        return (self.current_price - self.cost_basis) / self.cost_basis * 100


